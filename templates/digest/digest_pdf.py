"""Build the LaTeX + PDF edition of the paper digest from artifacts/mathematical/digest.md.

The Markdown file stays the single mathematical source of truth (write its mathematics as `$…$`
LaTeX); the LaTeX file is GENERATED from it by pandoc (never edit artifacts/mathematical/digest.tex
by hand) and compiled with LuaLaTeX via latexmk.

Input:   artifacts/mathematical/digest.md, scripts/digest_preamble.tex
Output:  artifacts/mathematical/digest.tex, artifacts/mathematical/digest.pdf
Usage:   python3 -I scripts/digest_pdf.py      (needs pandoc >= 3 and a TeX distribution with latexmk)
Environment (all optional): DIGEST_AUTHOR, DIGEST_SUBTITLE (e.g. the seminar and date),
         DIGEST_HEAD (running head), SITE_URL (printed under the title).
Publish the PDF, never the raw Markdown; render a few pages to PNG and look at them.
"""
from __future__ import annotations

import datetime
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "artifacts" / "mathematical" / "digest.md"
OUT = ROOT / "artifacts" / "mathematical"
BUILD = OUT / "_latex"                       # auxiliary files (git-ignore it)
PREAMBLE = ROOT / "scripts" / "digest_preamble.tex"


def main() -> int:
    for tool in ("pandoc", "latexmk", "lualatex"):
        if not shutil.which(tool):
            sys.exit(f"digest_pdf: {tool} not found")
    title = next((l[2:].strip() for l in SRC.read_text(encoding="utf-8").splitlines() if l.startswith("# ")), "Digest")
    head = os.environ.get("DIGEST_HEAD") or re.sub(r"[*_`]", "", title)[:80]
    author = os.environ.get("DIGEST_AUTHOR", "")
    subtitle = os.environ.get("DIGEST_SUBTITLE", "")
    site = os.environ.get("SITE_URL", "")
    today = datetime.date.today().strftime("%-d %B %Y")
    date = f"Generated from \\texttt{{digest.md}} on {today}" + (f"\\\\[2pt] \\url{{{site}}}" if site else "")
    with tempfile.NamedTemporaryFile("w", suffix=".tex", delete=False, encoding="utf-8") as pre:
        pre.write(PREAMBLE.read_text(encoding="utf-8").replace("RUNNING-HEAD", head.replace("&", "\\&")))
    tex = OUT / "digest.tex"
    cmd = ["pandoc", str(SRC), "--from", "markdown+tex_math_dollars+pipe_tables", "--to", "latex",
           "--standalone", "--shift-heading-level-by=-1", "--include-in-header", pre.name,
           "--variable", "documentclass=scrartcl", "--variable", "classoption=a4paper,11pt,DIV=13,parskip=half",
           "--variable", "lang=en", "--variable", f"date={date}", "--output", str(tex)]
    if author:
        cmd += ["--metadata", f"author={author}"]
    if subtitle:
        cmd += ["--metadata", f"subtitle={subtitle}"]
    subprocess.run(cmd, check=True)
    os.unlink(pre.name)
    s = tex.read_text(encoding="utf-8")
    tex.write_text("% GENERATED by scripts/digest_pdf.py from artifacts/mathematical/digest.md — do not edit.\n" + s,
                   encoding="utf-8")
    BUILD.mkdir(exist_ok=True)
    r = subprocess.run(["latexmk", "-lualatex", "-interaction=nonstopmode", "-halt-on-error",
                        f"-outdir={BUILD}", str(tex)], cwd=OUT, capture_output=True, text=True)
    log_path = BUILD / "digest.log"
    log = log_path.read_text(encoding="utf-8", errors="replace") if log_path.exists() else ""
    if r.returncode != 0:
        print(r.stdout[-3000:], r.stderr[-2000:])
        sys.exit("digest_pdf: LaTeX failed (see artifacts/mathematical/_latex/digest.log)")
    missing = sorted(set(re.findall(r"Missing character: There is no (\S+)", log)))
    overfull = len(re.findall(r"^Overfull \\hbox", log, re.M))
    shutil.copy2(BUILD / "digest.pdf", OUT / "digest.pdf")
    pages = re.search(r"Output written on .*?\((\d+) pages?", log)
    print(f"digest_pdf: {OUT / 'digest.pdf'} ({pages.group(1) if pages else '?'} pages); "
          f"missing characters: {missing or 'none'}; overfull hboxes: {overfull}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
